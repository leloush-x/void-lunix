#!/usr/bin/env bash
# voidc — in-target system configuration (run after packages are installed).

mount_chroot() {
  local d
  for d in dev proc sys run; do
    run "bind-mounting /$d" mkdir -p "$TARGET/$d"
    run "bind-mounting /$d into target" mount --rbind "/$d" "$TARGET/$d"
    try mount --make-rslave "$TARGET/$d"
  done
  if [ "$UEFI" = yes ]; then
    try modprobe efivarfs
    if ! mountpoint -q /sys/firmware/efi/efivars; then
      try mount -t efivarfs efivarfs /sys/firmware/efi/efivars
    fi
  fi
  verb "chroot mounts ready"
}

set_password() { # set_password <user> <password>  (via stdin, never argv)
  printf '%s:%s\n' "$1" "$2" | chroot "$TARGET" chpasswd -c SHA512 >>"$LOGFILE" 2>&1 \
    || die "Failed to set password for $1"
  verb "password set for $1"
}

write_hostname() {
  printf '%s\n' "$HOSTNAME" >"$TARGET/etc/hostname"
  cat >"$TARGET/etc/hosts" <<EOF
127.0.0.1   localhost
::1         localhost
127.0.1.1   $HOSTNAME.localdomain $HOSTNAME
EOF
  verb "hostname set to $HOSTNAME"
}

write_locale() {
  if [ "$LIBC" = glibc ]; then
    if [ -f "$TARGET/etc/default/libc-locales" ]; then
      awk -v loc="$LOCALE" '
        index($0, "#" loc " ") == 1 { sub(/^# ?/, "") }
        { print }
      ' "$TARGET/etc/default/libc-locales" >"$TARGET/etc/default/libc-locales.tmp" \
        && mv "$TARGET/etc/default/libc-locales.tmp" "$TARGET/etc/default/libc-locales"
    fi
    printf 'LANG=%s\n' "$LOCALE" >"$TARGET/etc/locale.conf"
    printf '# generated by voidc\n' >>"$TARGET/etc/locale.conf"
  fi
  verb "locale configured: $LOCALE"
}

write_keymap() {
  printf 'KEYMAP="%s"\n' "$KEYMAP" >"$TARGET/etc/voidc-keymap.conf"
  local rc="$TARGET/etc/rc.conf"
  if [ -f "$rc" ]; then
    sed -i -E "s|^#?KEYMAP=.*|KEYMAP=\"$KEYMAP\"|"            "$rc"
    sed -i -E "s|^#?HARDWARECLOCK=.*|HARDWARECLOCK=\"UTC\"|"   "$rc"
    sed -i -E "s|^#?TIMEZONE=.*|TIMEZONE=\"$TIMEZONE\"|"       "$rc"
  fi
  mkdir -p "$TARGET/etc/X11/xorg.conf.d"
  cat >"$TARGET/etc/X11/xorg.conf.d/00-keyboard.conf" <<EOF
Section "InputClass"
    Identifier "system-keyboard"
    MatchIsKeyboard "on"
    Option "XkbLayout" "$KEYMAP"
EndSection
EOF
  rm -f "$TARGET/etc/voidc-keymap.conf"
  verb "keymap configured: $KEYMAP"
}

write_timezone() {
  [ -f "$TARGET/usr/share/zoneinfo/$TIMEZONE" ] || die "Unknown timezone: $TIMEZONE"
  run "Linking localtime" ln -sf "/usr/share/zoneinfo/$TIMEZONE" "$TARGET/etc/localtime"
  printf '%s\n' "$TIMEZONE" >"$TARGET/etc/timezone"
  chroot_try "hwclock --systohc --utc"
  verb "timezone configured: $TIMEZONE"
}

create_users() {
  # keep only groups that exist in the target — an unknown group makes
  # useradd fail entirely, and group sets differ between systems
  local g grp_ok=""
  for g in wheel audio video input storage network optical kvm cdrom users; do
    grep -q "^$g:" "$TARGET/etc/group" 2>/dev/null && grp_ok+="$g,"
  done
  grp_ok="${grp_ok%,}"
  [ -n "$grp_ok" ] || grp_ok="wheel"
  chroot_run "useradd -m -U -G $grp_ok -s /bin/bash $USERNAME"
  chroot_run "passwd -l root >/dev/null 2>&1 || true"
  set_password root "$ROOT_PASS"
  set_password "$USERNAME" "$USER_PASS"

  mkdir -p "$TARGET/etc/sudoers.d"
  printf '%%wheel ALL=(ALL:ALL) ALL\nDefaults secure_path="/usr/local/sbin:/usr/local/bin:/usr/bin:/bin"\n' \
    >"$TARGET/etc/sudoers.d/10-wheel"
  chmod 0440 "$TARGET/etc/sudoers.d/10-wheel"
  chmod 0750 "$TARGET/etc/sudoers.d" 2>/dev/null || true
  if [ "${AUTOSTART_DESKTOP:-no}" = yes ]; then
    local acmd=""
    if desktop_uses_startx; then
      acmd="startx"
    elif desktop_uses_wayland; then
      acmd="dbus-run-session -- $(desktop_session_cmd)"
    fi
    if [ -n "$acmd" ]; then
      cat >>"$TARGET/home/$USERNAME/.bash_profile" <<EOF

# auto-start desktop on tty1 (added by voidc)
if [ -z "\$DISPLAY" ] && [ -z "\$WAYLAND_DISPLAY" ] && [ "\$(tty)" = "/dev/tty1" ]; then
    exec $acmd
fi
EOF
    fi
  fi
  chroot_run "chown -R $USERNAME:$USERNAME /home/$USERNAME"
  verb "user $USERNAME created"
}

# PipeWire, the official Void way (handbook): pipewire launches wireplumber
# and pipewire-pulse through system-wide config drop-ins; the desktop session
# starts pipewire (our WM presets do it; DEs use the XDG autostart entry).
setup_audio() {
  local pmdir="$TARGET/etc/pipewire/pipewire.conf.d"
  mkdir -p "$pmdir"
  [ -e "$TARGET/usr/share/examples/wireplumber/10-wireplumber.conf" ] && \
    ln -sf /usr/share/examples/wireplumber/10-wireplumber.conf "$pmdir/10-wireplumber.conf"
  [ -e "$TARGET/usr/share/examples/pipewire/20-pipewire-pulse.conf" ] && \
    ln -sf /usr/share/examples/pipewire/20-pipewire-pulse.conf "$pmdir/20-pipewire-pulse.conf"

  if [ -e "$TARGET/usr/share/applications/pipewire.desktop" ]; then
    mkdir -p "$TARGET/etc/xdg/autostart"
    ln -sf /usr/share/applications/pipewire.desktop "$TARGET/etc/xdg/autostart/pipewire.desktop"
  fi

  [ -d "$TARGET/etc/sv/rtkit" ] && enable_service rtkit
  verb "audio configured (pipewire drop-ins + xdg autostart)"
}

enable_system_services() {
  enable_service dbus
  enable_service elogind

  if in_list networking "$EXTRAS"; then
    local nm; nm="$(first_service NetworkManager networkmanager || true)"
    [ -n "$nm" ] && enable_service "$nm"
  fi
  in_list audio    "$EXTRAS" && setup_audio
  in_list ssh      "$EXTRAS" && enable_service sshd
  in_list bluetooth "$EXTRAS" && enable_service bluetoothd
  in_list printing "$EXTRAS" && enable_service cupsd
  enable_service chronyd 2>/dev/null || true

  local dm; dm="$(effective_dm)"
  if [ -n "$dm" ]; then
    enable_service "$dm"
    [ "$dm" = greetd ] && write_greetd_config
  fi
  verb "services enabled"
}

write_greetd_config() {
  local cmd; cmd="$(desktop_session_cmd)"
  mkdir -p "$TARGET/etc/greetd" "$TARGET/usr/local/bin"
  # wrapper so every session gets a D-Bus user bus (PipeWire needs one)
  cat >"$TARGET/usr/local/bin/voidc-session" <<EOF
#!/bin/sh
# generated by voidc — greetd session wrapper
export PATH=/usr/local/bin:/usr/bin:/bin
exec /usr/bin/dbus-run-session -- $cmd
EOF
  chmod 0755 "$TARGET/usr/local/bin/voidc-session"
  cat >"$TARGET/etc/greetd/config.toml" <<EOF
[terminal]
vt = 1

[default_session]
command = "tuigreet --time --remember --user-menu --asterisks --cmd /usr/local/bin/voidc-session"
user = "greeter"
EOF
  chroot_try "mkdir -p /var/cache/tuigreet && chown greeter:greeter /var/cache/tuigreet"
  verb "greetd configured (session: dbus-run-session -- $cmd)"
}

write_dracut_conf() {
  if [ "$LUKS" = yes ]; then
    mkdir -p "$TARGET/etc/dracut.conf.d"
    printf '# voidc: ensure crypt support in initramfs\nadd_dracutmodules+=" crypt "\n' \
      >"$TARGET/etc/dracut.conf.d/10-voidc-crypt.conf"
    verb "dracut crypt module enabled"
  fi
}

finalize_system() {
  ui_gauge_run " Finalizing " "Reconfiguring packages, building initramfs..." "$LOGFILE" \
    chroot "$TARGET" xbps-reconfigure -fa \
    || die "xbps-reconfigure failed — see $LOGFILE"
  verb "system finalized (initramfs built)"
}

configure_system() {
  write_hostname
  write_locale
  write_keymap
  write_timezone
  create_users
  enable_system_services
  write_dracut_conf
  verb "configuration complete"
}
