#!/usr/bin/env bash
# voidc — Wayland rice presets (hyprland / sway) + shared waybar/wofi/mako.

# gen_waybar <workspace-module>  (e.g. hyprland/workspaces, sway/workspaces)
gen_waybar() {
  local home="$TARGET/home/$USERNAME" cfg="$home/.config" mod="${1:-}"
  mkdir -p "$cfg/waybar"

  local left="[]"
  [ -n "$mod" ] && left="[\"$mod\"]"

  cat >"$cfg/waybar/config" <<EOF
{
    "layer": "top",
    "position": "top",
    "height": 28,
    "spacing": 6,
    "font-family": "DejaVu Sans",
    "modules-left": $left,
    "modules-center": ["clock"],
    "modules-right": ["cpu", "memory", "pulseaudio", "battery", "tray"],
    "cpu": { "interval": 2, "format": "CPU {usage}%" },
    "memory": { "interval": 2, "format": "MEM {percentage}%" },
    "pulseaudio": { "format": "VOL {volume}%", "format-muted": "VOL muted" },
    "battery": { "format": "BAT {capacity}%" },
    "clock": { "format": "%Y-%m-%d %H:%M" },
    "tray": { "icon-size": 14, "spacing": 8 }
}
EOF

  cat >"$cfg/waybar/style.css" <<'EOF'
* {
    font-family: "DejaVu Sans";
    font-size: 13px;
    border: none;
    border-radius: 0;
}
window#waybar {
    background: #1e1e2e;
    color: #cdd6f4;
}
#workspaces button {
    padding: 0 6px;
    color: #cdd6f4;
    background: transparent;
}
#workspaces button.focused,
#workspaces button.active {
    background: #89b4fa;
    color: #11111b;
    border-radius: 6px;
}
#clock, #cpu, #memory, #pulseaudio, #battery, #tray {
    padding: 0 8px;
}
#battery.warning { color: #f9e2af; }
#battery.critical { color: #f38ba8; }
EOF
}

gen_wofi() {
  local cfg="$TARGET/home/$USERNAME/.config"
  mkdir -p "$cfg/wofi"
  cat >"$cfg/wofi/config" <<'EOF'
width = 400
height = 300
prompt = Search
show = drun
allow_images = true
insensitive = true
EOF
  cat >"$cfg/wofi/style.css" <<'EOF'
window {
    background-color: #1e1e2e;
    border: 2px solid #89b4fa;
    border-radius: 8px;
}
#input {
    margin: 8px;
    padding: 6px;
    background: #313244;
    color: #cdd6f4;
    border: none;
    border-radius: 6px;
}
#inner-box { margin: 8px; }
#entry { padding: 4px; border-radius: 6px; }
#entry:selected {
    background-color: #89b4fa;
    color: #11111b;
}
EOF
}

gen_mako() {
  local cfg="$TARGET/home/$USERNAME/.config"
  mkdir -p "$cfg/mako"
  cat >"$cfg/mako/config" <<'EOF'
font=DejaVu Sans 10
background-color=#1e1e2e
text-color=#cdd6f4
border-color=#89b4fa
border-size=2
border-radius=6
default-timeout=6000
EOF
}

# ----------------------------------------------------------------- hyprland --
gen_hyprland() {
  local home="$TARGET/home/$USERNAME" cfg="$home/.config"
  mkdir -p "$cfg/hypr"

  cat >"$cfg/hypr/hyprland.conf" <<'EOF'
# Hyprland config — generated by voidc (safe to replace)
$mod = SUPER

monitor = , preferred, auto, 1

exec-once = waybar
exec-once = hyprpaper
exec-once = mako
exec-once = hypridle

general {
    gaps_in = 5
    gaps_out = 10
    border_size = 2
    col.active_border = rgba(89b4faee)
    col.inactive_border = rgba(45475aaa)
    layout = dwindle
}

decoration {
    rounding = 8
    blur {
        enabled = true
        size = 4
        passes = 2
    }
    drop_shadow = true
    shadow_range = 12
    shadow_render_power = 3
    col.shadow = rgba(11111b80)
}

animations {
    enabled = true
    bezier = ease, 0.25, 1, 0.5, 1
    animation = windows, 1, 3, ease
    animation = fade, 1, 3, ease
    animation = workspaces, 1, 3, ease
}

input {
    kb_layout = __KEYMAP__
    follow_mouse = 1
    touchpad {
        natural_scroll = true
    }
}

# apps
bind = $mod, RETURN, exec, foot
bind = $mod, D, exec, wofi --show drun
bind = $mod, L, exec, hyprlock

# window management
bind = $mod, Q, killactive
bind = $mod, F, fullscreen, 0
bind = $mod, V, togglefloating
bind = $mod, M, exit
bind = $mod, P, exec, hyprpicker -a
bind = $mod, S, exec, sh -c 'grim -g "$(slurp)" - | wl-copy'

# focus
bind = $mod, left, movefocus, l
bind = $mod, right, movefocus, r
bind = $mod, up, movefocus, u
bind = $mod, down, movefocus, d
bind = $mod, H, movefocus, l
bind = $mod, J, movefocus, d
bind = $mod, K, movefocus, u
bind = $mod, N, movefocus, r

# move windows
bind = $mod SHIFT, H, movewindow, l
bind = $mod SHIFT, J, movewindow, d
bind = $mod SHIFT, K, movewindow, u
bind = $mod SHIFT, N, movewindow, r

# workspaces
bind = $mod, 1, workspace, 1
bind = $mod, 2, workspace, 2
bind = $mod, 3, workspace, 3
bind = $mod, 4, workspace, 4
bind = $mod, 5, workspace, 5
bind = $mod, 6, workspace, 6
bind = $mod, 7, workspace, 7
bind = $mod, 8, workspace, 8
bind = $mod, 9, workspace, 9
bind = $mod, 0, workspace, 10
bind = $mod SHIFT, 1, movetoworkspace, 1
bind = $mod SHIFT, 2, movetoworkspace, 2
bind = $mod SHIFT, 3, movetoworkspace, 3
bind = $mod SHIFT, 4, movetoworkspace, 4
bind = $mod SHIFT, 5, movetoworkspace, 5
bind = $mod SHIFT, 6, movetoworkspace, 6
bind = $mod SHIFT, 7, movetoworkspace, 7
bind = $mod SHIFT, 8, movetoworkspace, 8
bind = $mod SHIFT, 9, movetoworkspace, 9
bind = $mod SHIFT, 0, movetoworkspace, 10

# mouse
bindm = $mod, mouse:272, movewindow
bindm = $mod, mouse:273, resizewindow

# media / brightness
bindl = , XF86AudioMute, exec, pamixer -t
bindl = , XF86AudioLowerVolume, exec, pamixer -d 5
bindl = , XF86AudioRaiseVolume, exec, pamixer -i 5
bindl = , XF86MonBrightnessUp, exec, brightnessctl set 5%+
bindl = , XF86MonBrightnessDown, exec, brightnessctl set 5%-
EOF
  sed -i "s/__KEYMAP__/$KEYMAP/" "$cfg/hypr/hyprland.conf"

  cat >"$cfg/hypr/hyprpaper.conf" <<EOF
preload = /home/$USERNAME/Pictures/wall.png
wallpaper = , /home/$USERNAME/Pictures/wall.png
splash = false
EOF

  cat >"$cfg/hypr/hypridle.conf" <<'EOF'
general {
    lock_cmd = pidof hyprlock || hyprlock
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = hyprctl dispatch dpms on
}

listener {
    timeout = 300
    on-timeout = hyprlock
}

listener {
    timeout = 600
    on-timeout = hyprctl dispatch dpms off
    on-resume = hyprctl dispatch dpms on
}
EOF

  cat >"$cfg/hypr/hyprlock.conf" <<'EOF'
background {
    monitor =
    color = rgba(17,17,27,0.95)
}

input-field {
    size = 220, 44
    outline_color = rgba(89b4faee)
    dots_center = true
    fade_on_empty = false
    placeholder_text = Password...
    check_color = rgba(166e3a1ee)
    fail_color = rgba(f38ba8ee)
}
EOF

  gen_waybar "hyprland/workspaces"
  gen_wofi
  gen_mako
  verb "hyprland preset generated"
}

# --------------------------------------------------------------------- sway --
gen_sway() {
  local home="$TARGET/home/$USERNAME" cfg="$home/.config"
  mkdir -p "$cfg/sway"

  cat >"$cfg/sway/config" <<'EOF'
# Sway config — generated by voidc (safe to replace)
set $mod Mod4
font pango:DejaVu Sans 10

set $bg     #1e1e2e
set $fg     #cdd6f4
set $accent #89b4fa

exec waybar
exec mako
exec sh -c '[ -f ~/Pictures/wall.png ] && swaybg -i ~/Pictures/wall.png -m fill'
exec swayidle -w \
    timeout 300 'swaylock -f' \
    timeout 600 'swaymsg "output * dpms off"' \
    resume 'swaymsg "output * dpms on"' \
    before-sleep 'swaylock -f'

input * xkb_layout __KEYMAP__
output * bg ~/Pictures/wall.png fill

bindsym $mod+Return exec foot
bindsym $mod+d exec wofi --show drun
bindsym $mod+Shift+q kill
bindsym $mod+f fullscreen toggle
bindsym $mod+Shift+space floating toggle

bindsym $mod+h focus left
bindsym $mod+j focus down
bindsym $mod+k focus up
bindsym $mod+l focus right
bindsym $mod+Shift+h move left
bindsym $mod+Shift+j move down
bindsym $mod+Shift+k move up
bindsym $mod+Shift+l move right

bindsym $mod+1 workspace number 1
bindsym $mod+2 workspace number 2
bindsym $mod+3 workspace number 3
bindsym $mod+4 workspace number 4
bindsym $mod+5 workspace number 5
bindsym $mod+6 workspace number 6
bindsym $mod+7 workspace number 7
bindsym $mod+8 workspace number 8
bindsym $mod+9 workspace number 9
bindsym $mod+0 workspace number 10
bindsym $mod+Shift+1 move container to workspace number 1
bindsym $mod+Shift+2 move container to workspace number 2
bindsym $mod+Shift+3 move container to workspace number 3
bindsym $mod+Shift+4 move container to workspace number 4
bindsym $mod+Shift+5 move container to workspace number 5
bindsym $mod+Shift+6 move container to workspace number 6
bindsym $mod+Shift+7 move container to workspace number 7
bindsym $mod+Shift+8 move container to workspace number 8
bindsym $mod+Shift+9 move container to workspace number 9
bindsym $mod+Shift+0 move container to workspace number 10

bindsym XF86AudioMute exec pamixer -t
bindsym XF86AudioLowerVolume exec pamixer -d 5
bindsym XF86AudioRaiseVolume exec pamixer -i 5
bindsym XF86MonBrightnessUp exec brightnessctl set 5%+
bindsym XF86MonBrightnessDown exec brightnessctl set 5%-
bindsym Print exec sh -c 'grim -g "$(slurp)" - | wl-copy'

gaps inner 8
gaps outer 4
smart_gaps on
default_border pixel 2
default_floating_border pixel 2
client.focused $accent $accent $bg $accent $accent
client.unfocused $bg $bg $fg $bg $bg
EOF
  sed -i "s/__KEYMAP__/$KEYMAP/" "$cfg/sway/config"

  gen_waybar "sway/workspaces"
  gen_wofi
  gen_mako
  verb "sway preset generated"
}

# --------------------------------------------------------------------- niri --
gen_niri() {
  local home="$TARGET/home/$USERNAME" cfg="$home/.config"
  mkdir -p "$cfg/niri"

  cat >"$cfg/niri/config.kdl" <<EOF
// niri config — generated by voidc (safe to replace)
// Based on niri's default config. Full reference:
// https://niri-wm.github.io/niri/Configuration:-Introduction

input {
    keyboard {
        xkb {
            layout "$KEYMAP"
        }
        numlock
    }
    touchpad {
        tap
        natural-scroll
    }
    // focus-follows-mouse
}

layout {
    gaps 8
    center-focused-column "never"
    preset-column-widths {
        proportion 0.33333
        proportion 0.5
        proportion 0.66667
    }
    default-column-width { proportion 0.5; }
    focus-ring {
        width 3
        active-color "#89b4fa"
        inactive-color "#45475a"
    }
    border {
        off
    }
    shadow {
        // on
        softness 30
        spread 5
        offset x=0 y=5
        color "#0007"
    }
}

spawn-at-startup "waybar"
spawn-at-startup "mako"
spawn-at-startup "swayidle" "-w" "timeout" "300" "swaylock -f" "timeout" "600" "niri msg action power-off-monitors" "resume" "niri msg action power-on-monitors" "before-sleep" "swaylock -f"
spawn-sh-at-startup "[ -f /home/$USERNAME/Pictures/wall.png ] && swaybg -i /home/$USERNAME/Pictures/wall.png -m fill || true"

hotkey-overlay {
    skip-at-startup
}

screenshot-path "/home/$USERNAME/Pictures/Screenshot from %Y-%m-%d %H-%M-%S.png"

binds {
    Mod+Shift+Slash { show-hotkey-overlay; }

    Mod+T hotkey-overlay-title="Open a Terminal: foot" { spawn "foot"; }
    Mod+D hotkey-overlay-title="Run an Application: wofi" { spawn "wofi" "--show" "drun"; }
    Super+Alt+L hotkey-overlay-title="Lock the Screen: swaylock" { spawn "swaylock"; }

    XF86AudioRaiseVolume allow-when-locked=true { spawn-sh "wpctl set-volume @DEFAULT_AUDIO_SINK@ 0.1+ -l 1.0"; }
    XF86AudioLowerVolume allow-when-locked=true { spawn-sh "wpctl set-volume @DEFAULT_AUDIO_SINK@ 0.1-"; }
    XF86AudioMute        allow-when-locked=true { spawn-sh "wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"; }
    XF86AudioMicMute     allow-when-locked=true { spawn-sh "wpctl set-mute @DEFAULT_AUDIO_SOURCE@ toggle"; }
    XF86MonBrightnessUp allow-when-locked=true { spawn "brightnessctl" "--class=backlight" "set" "+10%"; }
    XF86MonBrightnessDown allow-when-locked=true { spawn "brightnessctl" "--class=backlight" "set" "10%-"; }
    XF86TouchpadToggle repeat=false { toggle-touchpad; }

    Mod+O repeat=false { toggle-overview; }
    Mod+Q repeat=false { close-window; }
    Alt+F4 repeat=false { close-window; }

    Mod+Left  { focus-column-left; }
    Mod+Down  { focus-window-down; }
    Mod+Up    { focus-window-up; }
    Mod+Right { focus-column-right; }
    Mod+H     { focus-column-left; }
    Mod+J     { focus-window-down; }
    Mod+K     { focus-window-up; }
    Mod+L     { focus-column-right; }

    Mod+Ctrl+H     { move-column-left; }
    Mod+Ctrl+J     { move-window-down; }
    Mod+Ctrl+K     { move-window-up; }
    Mod+Ctrl+L     { move-column-right; }

    Mod+Home { focus-column-first; }
    Mod+End  { focus-column-last; }
    Mod+Ctrl+Home { move-column-to-first; }
    Mod+Ctrl+End  { move-column-to-last; }

    Mod+Shift+H     { focus-monitor-left; }
    Mod+Shift+J     { focus-monitor-down; }
    Mod+Shift+K     { focus-monitor-up; }
    Mod+Shift+L     { focus-monitor-right; }
    Mod+Shift+Ctrl+H     { move-column-to-monitor-left; }
    Mod+Shift+Ctrl+J     { move-column-to-monitor-down; }
    Mod+Shift+Ctrl+K     { move-column-to-monitor-up; }
    Mod+Shift+Ctrl+L     { move-column-to-monitor-right; }

    Mod+Page_Down      { focus-workspace-down; }
    Mod+Page_Up        { focus-workspace-up; }
    Mod+U              { focus-workspace-down; }
    Mod+I              { focus-workspace-up; }
    Mod+Ctrl+Page_Down { move-column-to-workspace-down; }
    Mod+Ctrl+Page_Up   { move-column-to-workspace-up; }
    Mod+Ctrl+U         { move-column-to-workspace-down; }
    Mod+Ctrl+I         { move-column-to-workspace-up; }

    Mod+WheelScrollDown      cooldown-ms=150 { focus-workspace-down; }
    Mod+WheelScrollUp        cooldown-ms=150 { focus-workspace-up; }
    Mod+Ctrl+WheelScrollDown cooldown-ms=150 { move-column-to-workspace-down; }
    Mod+Ctrl+WheelScrollUp   cooldown-ms=150 { move-column-to-workspace-up; }
    Mod+WheelScrollRight      { focus-column-right; }
    Mod+WheelScrollLeft       { focus-column-left; }
    Mod+Ctrl+WheelScrollRight { move-column-right; }
    Mod+Ctrl+WheelScrollLeft  { move-column-left; }

    Mod+1 { focus-workspace 1; }
    Mod+2 { focus-workspace 2; }
    Mod+3 { focus-workspace 3; }
    Mod+4 { focus-workspace 4; }
    Mod+5 { focus-workspace 5; }
    Mod+6 { focus-workspace 6; }
    Mod+7 { focus-workspace 7; }
    Mod+8 { focus-workspace 8; }
    Mod+9 { focus-workspace 9; }
    Mod+Ctrl+1 { move-column-to-workspace 1; }
    Mod+Ctrl+2 { move-column-to-workspace 2; }
    Mod+Ctrl+3 { move-column-to-workspace 3; }
    Mod+Ctrl+4 { move-column-to-workspace 4; }
    Mod+Ctrl+5 { move-column-to-workspace 5; }
    Mod+Ctrl+6 { move-column-to-workspace 6; }
    Mod+Ctrl+7 { move-column-to-workspace 7; }
    Mod+Ctrl+8 { move-column-to-workspace 8; }
    Mod+Ctrl+9 { move-column-to-workspace 9; }

    Mod+BracketLeft  { consume-or-expel-window-left; }
    Mod+BracketRight { consume-or-expel-window-right; }
    Mod+Comma  { consume-window-into-column; }
    Mod+Period { expel-window-from-column; }

    Mod+R { switch-preset-column-width; }
    Mod+Shift+R { switch-preset-column-width-back; }
    Mod+F { maximize-column; }
    Mod+Shift+F { fullscreen-window; }
    Mod+M { maximize-window-to-edges; }
    Mod+Ctrl+F { expand-column-to-available-width; }
    Mod+C { center-column; }

    Mod+Minus { set-column-width "-10%"; }
    Mod+Equal { set-column-width "+10%"; }
    Mod+Shift+Minus { set-window-height "-10%"; }
    Mod+Shift+Equal { set-window-height "+10%"; }

    Mod+V       { toggle-window-floating; }
    Mod+Shift+V { switch-focus-between-floating-and-tiling; }
    Mod+W { toggle-column-tabbed-display; }

    Print { screenshot; }
    Ctrl+Print { screenshot-screen; }
    Alt+Print { screenshot-window; }

    Mod+Escape allow-inhibiting=false { toggle-keyboard-shortcuts-inhibit; }
    Mod+Shift+E { quit; }
    Ctrl+Alt+Delete { quit; }
    Mod+Shift+P { power-off-monitors; }
}
EOF

  gen_waybar ""
  gen_wofi
  gen_mako
  verb "niri preset generated"
}
