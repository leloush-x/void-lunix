#!/usr/bin/env bash
# voidc — post-install desktop polish: dotfiles, matugen, generated configs.
# Consumes: DESKTOP USERNAME DOTFILES_URL RUN_DOTFILES_INSTALL

# install_matugen — try repo first, then a prebuilt GitHub release binary.
install_matugen() {
  if xbps-query -r "$TARGET" matugen >/dev/null 2>&1; then
    verb "matugen already installed (repo)"; return 0
  fi
  if xbps-query -R matugen >/dev/null 2>&1; then
    say "Installing matugen (repo)"
    try xbps-install -y -r "$TARGET" matugen
    return 0
  fi

  say "matugen not in repos — fetching prebuilt release"
  local dl=""
  if command -v curl >/dev/null 2>&1; then
    local arch_pat="x86_64"
    local libc_pat="gnu"; [ "$LIBC" = musl ] && libc_pat="musl"

    # Asset names changed across releases ("matugen-4.2.0-x86_64.tar.gz",
    # "matugen-x86_64-unknown-linux-gnu.tar.gz", ...): match the arch token
    # and prefer the build matching the target libc.
    local urls assets url base
    urls="$(curl -fsSL -m 20 https://api.github.com/repos/InioX/matugen/releases/latest 2>>"$LOGFILE" \
            | grep -oE '"browser_download_url": *"[^"]+' \
            | cut -d'"' -f4 \
            | grep -vE '\.(sha256|sig|asc)$' || true)"
    assets=""
    while IFS= read -r url; do
      [ -n "$url" ] || continue
      base="${url##*/}"
      case "$base" in *"$arch_pat"*) assets="${assets}${url}"$'\n' ;; esac
    done <<< "$urls"
    if [ "$libc_pat" = musl ]; then
      # never install a non-musl build on musl — it cannot run
      dl="$(printf '%s' "$assets" | grep -i musl | head -n1 || true)"
    else
      dl="$(printf '%s' "$assets" | grep -i -v musl | head -n1 || true)"
      [ -n "$dl" ] || dl="$(printf '%s' "$assets" | head -n1 || true)"
    fi
  fi

  if [ -z "$dl" ]; then
    warnlog "could not resolve a matugen release asset — skipped (install later via 'cargo install matugen')"
    return 0
  fi

  local tmp; tmp="$(mktemp -d)"
  if ! curl -fsSL -m 120 -o "$tmp/matugen.dl" "$dl" >>"$LOGFILE" 2>&1; then
    warnlog "matugen download failed — skipped"; rm -rf "$tmp"; return 0
  fi
  case "$dl" in
    *.tar.gz|*.tgz)
      tar -xzf "$tmp/matugen.dl" -C "$tmp" >>"$LOGFILE" 2>&1 || { warnlog "matugen extract failed"; rm -rf "$tmp"; return 0; }
      local bin; bin="$(find "$tmp" -type f -name 'matugen*' ! -name '*.dl' | head -n1)"
      ;;
    *) bin="$tmp/matugen.dl" ;;
  esac
  if [ -n "${bin:-}" ] && [ -s "$bin" ]; then
    install -Dm0755 "$bin" "$TARGET/usr/local/bin/matugen"
    verb "matugen installed to /usr/local/bin"
  else
    warnlog "matugen binary not found in download — skipped"
  fi
  rm -rf "$tmp"
}

# clone_dotfiles — clone the user's dotfiles repo into their home.
clone_dotfiles() {
  [ -n "${DOTFILES_URL:-}" ] || return 0
  local dest="$TARGET/home/$USERNAME/.dotfiles"
  say "Cloning dotfiles"
  if command -v git >/dev/null 2>&1; then
    try git clone --depth 1 "$DOTFILES_URL" "$dest"
  elif [ -x "$TARGET/usr/bin/git" ]; then
    chroot_try "git clone --depth 1 '$DOTFILES_URL' '/home/$USERNAME/.dotfiles'"
  else
    warnlog "git unavailable — dotfiles not cloned"; return 0
  fi
  [ -d "$dest" ] || { warnlog "dotfiles clone failed"; return 0; }

  if [ "${RUN_DOTFILES_INSTALL:-no}" = yes ]; then
    say "Running dotfiles installer (as $USERNAME)"
    chroot_try "su -l $USERNAME -c 'cd ~/.dotfiles && { [ -x install.sh ] && ./install.sh || [ -x setup.sh ] && ./setup.sh || true; }'"
  fi
}

# ---------------------------------------------------------------- wallpaper --
install_wallpaper() {
  local home="$TARGET/home/$USERNAME" src="$VOIDC_DIR/assets/wall.png.b64"
  mkdir -p "$home/Pictures"
  if [ -f "$src" ] && command -v base64 >/dev/null 2>&1; then
    base64 -d "$src" >"$home/Pictures/wall.png" 2>>"$LOGFILE" || warnlog "wallpaper decode failed"
  fi
}

